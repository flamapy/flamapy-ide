#!/usr/bin/env python3
"""Print the wheels the IDE boots by default, for a native (non-Pyodide) test env.

Reads the served ``plugins.conf.json`` (generated by ``make build-wheels``) and prints,
one path per line, the core wheels plus those of every plugin that is ``preinstalled``
and ``available`` -- the set ``public/flamapy/flamapy.js`` boots for a new user.
Optional plugins (SDD, #SAT, ...) are left out: the tests don't exercise them, and their
native dependencies (pysdd, pyunigen) only ship here as WebAssembly wheels.

WebAssembly wheels are skipped too, as they cannot install natively; their native
equivalents (python-sat, z3-solver) come from ``requirements.txt``. Usage::

    pip install --no-deps $(python3 scripts/default_boot_wheels.py)

Environment:
    FLAMAPY_WHEELS_DIR   wheels directory (default: public/flamapy)
"""
import json
import os
import sys
from pathlib import Path

WHEELS_DIR = Path(os.environ.get("FLAMAPY_WHEELS_DIR", "public/flamapy"))
CONF_PATH = WHEELS_DIR / "plugins.conf.json"


def default_boot_wheels(conf: dict) -> list[str]:
    """Core wheels + the wheels of the plugins booted by default, in manifest order."""
    wheels = list(conf["core"]["wheels"])
    for plugin in conf["plugins"]:
        if plugin.get("preinstalled") and plugin.get("available", True):
            wheels += plugin["wheels"]
    return [wheel for wheel in wheels if "wasm32" not in wheel]


def main() -> int:
    if not CONF_PATH.exists():
        print(f"{CONF_PATH} not found: run `make build-wheels` first.", file=sys.stderr)
        return 1
    conf = json.loads(CONF_PATH.read_text())
    for wheel in default_boot_wheels(conf):
        print(wheel if "://" in wheel else WHEELS_DIR / wheel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
